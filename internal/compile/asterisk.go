// pjsipNotifyConf holds Cisco's service-control NOTIFY bodies for trying by
// hand (pjsip send notify cisco-restart endpoint <ID>). The agent sends its
// own over AMI PJSIPNotify with the contact's RegisterCallId, which a static
// stanza cannot know. res_pjsip_notify declines to load without this file.
func pjsipNotifyConf() []byte {
	w := newConf()
	w.comment("Cisco service-control NOTIFYs, for use by hand:\n" +
		"  pjsip send notify cisco-restart endpoint phone-<name>   (re-read config)\n" +
		"  pjsip send notify cisco-reset endpoint phone-<name>     (reboot)\n" +
		"The agent sends its own over AMI, adding the contact's RegisterCallId.")
	for _, s := range []struct{ name, action string }{{pjsipNotifyRestart, "restart"}, {pjsipNotifyReset, "reset"}} {
		w.section(s.name)
		w.arrow("Event", "service-control")
		w.arrow("Subscription-State", "active")
		w.arrow("Content-Type", "text/plain")
		w.arrow("Content", "action="+s.action)
		for _, stamp := range []string{"ConfigVersionStamp", "DialplanVersionStamp", "SoftkeyVersionStamp", "FeatureControlVersionStamp"} {
			w.arrow("Content", stamp+"={00000000-0000-0000-0000-000000000000}")
		}
		w.arrow("Content", "HeadsetVersionStamp={0-0000000000}")
	}
	return w.bytes()
}

// managerConf is AMI for the agent alone (the package documentation's
// manager.conf rules).
func managerConf(secret SecretRef) []byte {
	w := newConf()
	w.comment("AMI on 127.0.0.1. The PBX pod is on the host network, so this is the\n" +
		"node's loopback and any host-network process there can connect. The\n" +
		"account's generated secret is the barrier: its system class, which the\n" +
		"agent needs, also loads modules and adds dialplan, so whoever holds\n" +
		"the secret controls this PBX.")
	w.section("general")
	w.set("enabled", "yes")
	w.set("bindaddr", "127.0.0.1")
	w.set("port", strconv.Itoa(AMIPort))
	w.set("displayconnects", "no")
	w.section(AMIUsername)
	w.set("secret", secret.Placeholder())
	w.set("deny", "0.0.0.0/0.0.0.0")
	w.set("permit", "127.0.0.1/255.255.255.255")
	w.set("read", AMIClasses)
	w.set("write", AMIClasses)
	return w.bytes()
}

// pjsipConf is the SIP side: two transports on the PBX address, the ACL,
// and per routed, rendered device an endpoint (named by its ID), an auth
// (username = ID) and an AOR (named by its number).
func pjsipConf(s Settings, endpoints []endpoint) []byte {
	bind := fmt.Sprintf("%s:%d", s.PBXAddress, s.SIPPort)
	w := newConf()
	w.section("global")
	w.set("type", "global")
	w.set("user_agent", "patchbay")
	w.comment("A device is identified by the username of its digest Authorization:\n" +
		"its ID. The first request of a dialog carries none, so it is challenged\n" +
		"first (in realm default_realm), then matched.")
	w.set("default_realm", SIPRealm)
	w.set("endpoint_identifier_order", "auth_username")

	for _, t := range []struct {
		name     string
		protocol drivers.SIPTransport
	}{{TransportUDP, drivers.SIPTransportUDP}, {TransportTCP, drivers.SIPTransportTCP}} {
		w.section(t.name)
		w.set("type", "transport")
		w.set("protocol", string(t.protocol))
		w.set("bind", bind)
	}

	w.section(ACLName)
	w.comment("Every SIP request from anywhere but these networks is refused.")
	w.set("type", "acl")
	w.set("deny", "0.0.0.0/0.0.0.0")
	for _, n := range s.AllowedNetworks {
		w.set("permit", n)
	}

	for _, e := range endpoints {
		d, o := e.dev, e.profile.Endpoint
		w.section(d.ID, fmt.Sprintf("%s %s, number %s", d.Kind, d.Name, d.Number))
		w.set("type", "endpoint")
		w.set("context", DevicesContext)
		w.set("transport", transportName(o.Transport))
		w.set("aors", d.Number)
		w.set("auth", d.ID)
		w.set("identify_by", "auth_username")
		w.set("callerid", callerID(d.Label, d.Number, e.profile.Provisioning.LineLabelMax))
		w.set("disallow", "all")
		w.set("allow", strings.Join(o.Codecs, ","))
		w.set("dtmf_mode", "rfc4733")
		w.set("media_address", s.PBXAddress)
		w.bool("bind_rtp_to_media_address", true)
		w.bool("direct_media", o.DirectMedia)
		w.bool("force_rport", o.ForceRport)
		w.bool("rewrite_contact", o.RewriteContact)
		w.bool("rtp_symmetric", o.RTPSymmetric)
		w.bool("send_rpid", o.SendRPID)
		w.bool("send_pai", o.SendPAI)
		w.bool("trust_id_inbound", false)
		w.bool("trust_id_outbound", o.TrustIDOutbound)
		w.set("contact_deny", "0.0.0.0/0.0.0.0")
		for _, n := range s.AllowedNetworks {
			w.set("contact_permit", n)
		}

		w.section(d.ID)
		w.set("type", "auth")
		w.set("auth_type", "digest")
		w.set("username", d.ID)
		w.set("password", PasswordRef(d.ID).Placeholder())

		expiry := strconv.Itoa(int(o.RegistrationExpiry / time.Second))
		w.section(d.Number)
		w.set("type", "aor")
		w.set("max_contacts", "1")
		w.bool("remove_existing", true)
		w.set("default_expiration", expiry)
		w.set("maximum_expiration", expiry)
		w.set("qualify_frequency", strconv.Itoa(int(o.QualifyFrequency/time.Second)))
	}
	return w.bytes()
}

func transportName(t drivers.SIPTransport) string {
	if t == drivers.SIPTransportTCP {
		return TransportTCP
	}
	return TransportUDP
}
