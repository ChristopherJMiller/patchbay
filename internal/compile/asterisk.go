// confWriter writes an Asterisk config file: sections of "key = value" (or
// "key => value") lines. Values must already be escaped (confValue).
type confWriter struct {
	b bytes.Buffer
}

func newConf() *confWriter {
	w := &confWriter{}
	w.b.WriteString(generatedHeader)
	return w
}

// comment writes "; text" lines, one per line of text.
func (w *confWriter) comment(text string) {
	for line := range strings.SplitSeq(text, "\n") {
		w.b.WriteString(strings.TrimRight("; "+line, " ") + "\n")
	}
}

// section starts a section after a blank line, with a comment above it
// when one is given.
func (w *confWriter) section(name string, comment ...string) {
	w.b.WriteString("\n")
	for _, c := range comment {
		w.comment(c)
	}
	w.b.WriteString("[" + name + "]\n")
}

func (w *confWriter) set(key, value string)   { w.b.WriteString(key + " = " + value + "\n") }
func (w *confWriter) arrow(key, value string) { w.b.WriteString(key + " => " + value + "\n") }
func (w *confWriter) bool(key string, v bool) { w.set(key, yesNo(v)) }
func (w *confWriter) bytes() []byte           { return w.b.Bytes() }

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

// confValue escapes text for the value of an Asterisk config line: ";"
// starts a comment (";--" even a block comment) unless written "\;", and a
// control character would end the line, so each becomes a space.
func confValue(v string) string {
	v = strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, v)
	return strings.ReplaceAll(v, ";", `\;`)
}

// CallerIDName is the caller ID name Asterisk sends for a label: cut to max
// characters, with '"' written as "'" and '\' as '/' (Asterisk's caller ID
// parser has no escape for either inside the quotes) and control
// characters as spaces. Not yet escaped for a config line.
func CallerIDName(label string, maxLen int) string {
	name := strings.Map(func(r rune) rune {
		switch {
		case r == '"':
			return '\''
		case r == '\\':
			return '/'
		case unicode.IsControl(r):
			return ' '
		}
		return r
	}, label)
	if runes := []rune(name); maxLen > 0 && len(runes) > maxLen {
		name = string(runes[:maxLen])
	}
	return name
}

// callerID is a pjsip `callerid` value: "<name>" <<number>>, escaped.
// Asterisk takes the last "<" as the start of the number, so a name may
// hold "<" and ">".
func callerID(label, number string, maxLen int) string {
	return confValue(`"` + CallerIDName(label, maxLen) + `" <` + number + `>`)
}

// endpoint is one routed, rendered device as pjsip.conf sees it.
type endpoint struct {
	dev     drivers.Device
	profile drivers.Profile
}

// asteriskFiles renders every file of the asterisk/ tree but the dialplan.
// endpoints must be sorted by device ID.
func asteriskFiles(s Settings, endpoints []endpoint) map[string][]byte {
	return map[string][]byte{
		TreeAsterisk + "/asterisk.conf":     asteriskConf(),
		TreeAsterisk + "/modules.conf":      modulesConf(),
		TreeAsterisk + "/logger.conf":       loggerConf(),
		TreeAsterisk + "/cdr.conf":          disabledConf("Call records are off; nothing reads them.", "enable"),
		TreeAsterisk + "/cel.conf":          disabledConf("Channel event logging is off; nothing reads it.", "enable"),
		TreeAsterisk + "/http.conf":         disabledConf("Asterisk's HTTP server (and so ARI) is off.", "enabled"),
		TreeAsterisk + "/rtp.conf":          rtpConf(s.RTPPorts),
		TreeAsterisk + "/indications.conf":  indicationsConf(),
		TreeAsterisk + "/pjsip_notify.conf": pjsipNotifyConf(),
		TreeAsterisk + "/manager.conf":      managerConf(s.AMISecret),
		TreeAsterisk + "/pjsip.conf":        pjsipConf(s, endpoints),
		// Files Asterisk's core reads whether or not anything is set in
		// them: without them it logs an ERROR at every start. Empty means
		// Asterisk's defaults.
		TreeAsterisk + "/acl.conf":       defaultsConf("Named ACLs: none (pjsip.conf has its own)."),
		TreeAsterisk + "/ccss.conf":      defaultsConf("Call completion: Asterisk's defaults."),
		TreeAsterisk + "/features.conf":  defaultsConf("Call features: Asterisk's defaults (none bound to keys)."),
		TreeAsterisk + "/pjproject.conf": defaultsConf("pjproject: Asterisk's defaults."),
		TreeAsterisk + "/stasis.conf":    defaultsConf("Stasis message bus: Asterisk's defaults."),
		TreeAsterisk + "/udptl.conf":     defaultsConf("UDPTL (fax): Asterisk's defaults."),
	}
}

// defaultsConf is a file that exists only so Asterisk finds it.
func defaultsConf(why string) []byte {
	w := newConf()
	w.comment(why)
	return w.bytes()
}

func asteriskConf() []byte {
	w := newConf()
	w.comment("Asterisk runs as uid 1000 on a read-only root filesystem: everything it\n" +
		"writes goes to the PBX pod's emptyDirs. Its config is this directory,\n" +
		"through the live directory's current symlink, so a reload after the agent\n" +
		"swaps versions reads the new one.")
	w.section("directories")
	for _, d := range [][2]string{
		{"astetcdir", AsteriskConfigDir},
		{"astmoddir", AsteriskModuleDir},
		{"astvarlibdir", "/var/lib/asterisk"},
		{"astdatadir", "/var/lib/asterisk"},
		{"astkeydir", "/var/lib/asterisk"},
		{"astagidir", "/var/lib/asterisk/agi-bin"},
		{"astsbindir", "/usr/sbin"},
		{"astrundir", "/var/run/asterisk"},
		{"astlogdir", "/var/log/asterisk"},
		{"astspooldir", "/var/spool/asterisk"},
		{"astdbdir", "/var/spool/asterisk"},
		{"astcachedir", "/var/spool/asterisk"},
	} {
		w.arrow(d[0], d[1])
	}
	w.section("options")
	w.set("documentation_language", "en_US")
	w.set("hideconnect", "yes")
	return w.bytes()
}

// Modules lists every module modules.conf loads, in its order. Nothing else
// loads (autoload = no), and in the PBX pod nothing else is even present:
// the chart copies exactly these files from the Asterisk image into the
// volume it mounts at AsteriskModuleDir, and a test keeps the chart's list
// equal to this one. None of them can run a shell command.
func Modules() []string {
	var out []string
	for _, g := range modules {
		out = append(out, g.Modules...)
	}
	return out
}

func modulesConf() []byte {
	w := newConf()
	w.comment("Only these modules load: none of the image's defaults.")
	w.section("modules")
	w.set("autoload", "no")
	for _, g := range modules {
		w.b.WriteString("\n")
		w.comment(g.Group)
		for _, m := range g.Modules {
			w.arrow("load", m)
		}
	}
	return w.bytes()
}

func loggerConf() []byte {
	w := newConf()
	w.section("general")
	w.set("dateformat", "%F %T.%3q")
	w.section("logfiles")
	w.comment("The container log. -v on the command line sets the verbosity.")
	w.arrow("console", "notice,warning,error,verbose")
	return w.bytes()
}

func disabledConf(why, key string) []byte {
	w := newConf()
	w.comment(why)
	w.section("general")
	w.set(key, "no")
	return w.bytes()
}

func rtpConf(ports PortRange) []byte {
	w := newConf()
	w.section("general")
	w.set("rtpstart", strconv.Itoa(ports.First))
	w.set("rtpend", strconv.Itoa(ports.Last))
	return w.bytes()
}

