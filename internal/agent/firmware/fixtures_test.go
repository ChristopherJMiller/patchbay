// fakeDriver is the smallest drivers.Driver with a firmware manifest and a
// default load per model: enough for NewRegistry and the store.
type fakeDriver struct {
	name     string
	defaults map[string]string // model -> profile DefaultFirmware
	loads    []drivers.FirmwareLoad
}

func (f fakeDriver) Name() string { return f.name }

func (f fakeDriver) Models() []string {
	out := make([]string, 0, len(f.defaults))
	for m := range f.defaults {
		out = append(out, m)
	}
	slices.Sort(out)
	return out
}

func (f fakeDriver) Profile(model string) (drivers.Profile, bool) {
	def, ok := f.defaults[model]
	if !ok {
		return drivers.Profile{}, false
	}
	return drivers.Profile{
		Model: model,
		Provisioning: drivers.Provisioning{
			DefaultFirmware: def,
			Password:        drivers.PasswordPolicy{Length: 12, Alphabet: drivers.Alphanumeric},
		},
		Endpoint: drivers.EndpointOptions{
			Transport:          drivers.SIPTransportTCP,
			Codecs:             []string{"ulaw"},
			RegistrationExpiry: time.Hour,
		},
	}, true
}

func (fakeDriver) Render(drivers.Device, drivers.RenderContext) (drivers.Files, error) {
	return nil, nil
}

func (fakeDriver) Decide(dev drivers.Device, _ drivers.Observations, _ drivers.DecideSettings, _ time.Time) drivers.Decision {
	return drivers.Decision{State: dev.LastState, StatusPatch: dev.Memory}
}

func (f fakeDriver) Firmware() []drivers.FirmwareLoad { return f.loads }

// content is the generated bytes of one file of one load: never anything
// real. Two loads' copies of a Shared name differ, as Cisco's do.
func content(load, name string) []byte {
	line := "patchbay test firmware " + load + "/" + name + "\n"
	return []byte(strings.Repeat(line, 64))
}

func digest(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

// file is a manifest entry whose digest is that of content(load, name).
func file(load, name string, shared bool) drivers.FirmwareFile {
	b := content(load, name)
	return drivers.FirmwareFile{Name: name, SHA256: digest(b), Size: int64(len(b)), Shared: shared}
}

func pending(name string, shared bool) drivers.FirmwareFile {
	return drivers.FirmwareFile{Name: name, SHA256: drivers.SHA256Pending, Size: 100, Shared: shared}
}

// The test registry:
//
//	alpha (models alpha-1, alpha-2: default load A1; alpha-3: default "gone",
//	       a load in no manifest)
//	  A1  a1.loads, appsA1.sbn, term.default.loads (Shared), both.default.loads (Shared)
//	  A2  a2.loads, appsA2.sbn, term.default.loads (Shared), orphan.default.loads (Shared)
//	  A3  a3.loads (pending), orphan.default.loads (Shared)
//	beta (model beta-1: default load B1)
//	  B1  b1.sbn (its manifest size wrong), both.default.loads (Shared), pend.default.loads (Shared, pending)
//
// So term.default.loads resolves to A1 (the one default load carrying it),
// both.default.loads to nothing (two default loads), orphan.default.loads
// to nothing (no default load carries it).
func testLoads() (alpha, beta []drivers.FirmwareLoad) {
	alpha = []drivers.FirmwareLoad{
		{Name: "A1", Models: []string{"alpha-1", "alpha-2"}, Files: []drivers.FirmwareFile{
			file("A1", "a1.loads", false), file("A1", "appsA1.sbn", false),
			file("A1", "term.default.loads", true), file("A1", "both.default.loads", true),
		}},
		{Name: "A2", Models: []string{"alpha-1"}, Files: []drivers.FirmwareFile{
			file("A2", "a2.loads", false), file("A2", "appsA2.sbn", false),
			file("A2", "term.default.loads", true), file("A2", "orphan.default.loads", true),
		}},
		{Name: "A3", Models: []string{"alpha-2"}, Files: []drivers.FirmwareFile{
			pending("a3.loads", false), file("A3", "orphan.default.loads", true),
		}},
	}
	beta = []drivers.FirmwareLoad{
		{Name: "B1", Models: []string{"beta-1"}, Files: []drivers.FirmwareFile{
			wrongSize(file("B1", "b1.sbn", false)), file("B1", "both.default.loads", true),
			pending("pend.default.loads", true),
		}},
	}
	return alpha, beta
}

func testRegistry(t *testing.T) *drivers.Registry {
	t.Helper()
	alpha, beta := testLoads()
	reg, err := drivers.NewRegistry(
		fakeDriver{name: "alpha", defaults: map[string]string{"alpha-1": "A1", "alpha-2": "A1", "alpha-3": "gone"}, loads: alpha},
		fakeDriver{name: "beta", defaults: map[string]string{"beta-1": "B1"}, loads: beta},
	)
	if err != nil {
		t.Fatal(err)
	}
	return reg
}

func testManifest(t *testing.T) *firmware.Manifest {
	t.Helper()
	m, err := firmware.NewManifest(testRegistry(t))
	if err != nil {
		t.Fatal(err)
	}
	return m
}

// wrongSize gives f a manifest size its bytes do not have: the size is
// advisory, and nothing may enforce it.
func wrongSize(f drivers.FirmwareFile) drivers.FirmwareFile {
	f.Size++
	return f
}
